use time::OffsetDateTime;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TenantKind {
    Organization,
    Individual,
}

impl TenantKind {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Organization => "organization",
            Self::Individual => "individual",
        }
    }
}

/// New tenant. Ids are generated by the caller *before* insert because encrypted columns bind
/// them in their AAD (DATABASE.md §3).
#[derive(Clone, Debug)]
pub struct NewTenant {
    pub id: TenantId,
    pub kind: TenantKind,
    pub display_name_enc: Vec<u8>,
}

#[derive(Clone, Debug)]
pub struct NewOwner {
    pub membership_id: MembershipId,
    pub user_id: UserId,
    pub display_name_enc: Option<Vec<u8>>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CreatedTenant {
    pub tenant: TenantId,
    pub owner: MembershipId,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TenantRow {
    pub id: TenantId,
    pub kind: String,
    pub status: String,
    pub version: u32,
    pub created_at: OffsetDateTime,
}

/// Create a tenant with its bootstrap rows (epoch, settings, quotas = unlimited, counters) and the
/// first owner membership (+ directory), all in one system transaction.
///
/// # Errors
/// `Invalid` (nil ids), `NotFound("user")`, `Conflict("tenants.id_taken")`, server errors.
pub async fn create(
    tx: &mut SystemTx,
    t: &NewTenant,
    owner: &NewOwner,
    now: OffsetDateTime,
) -> Result<CreatedTenant, DbError> {
    if t.id.0.is_nil() || owner.membership_id.0.is_nil() {
        return Err(DbError::Invalid("ids must not be nil"));
    }
    if t.id == crate::PLATFORM_TENANT_ID {
        return Err(DbError::Invalid("platform pseudo-tenant id is reserved"));
    }
    let tid = t.id.0;
    let inner = &mut tx.inner;
    match inner
        .execute(
            sql::q(TENANTS_INSERT)
                .bind(tid)
                .bind(t.kind.as_str())
                .bind(t.display_name_enc.as_slice())
                .bind(now)
                .bind(now),
        )
        .await
    {
        Ok(n) => n.expect_one()?,
        Err(e) if e.is_duplicate_of("PRIMARY") => {
            return Err(DbError::Conflict("tenants.id_taken"));
        }
        Err(e) => return Err(e),
    }
    for q in [
        AUTHZ_EPOCHS_INSERT,
        TENANT_SETTINGS_INSERT,
        TENANT_QUOTAS_INSERT,
        TENANT_COUNTERS_INSERT,
    ] {
        inner
            .execute(sql::q(q).bind(tid).bind(now))
            .await?
            .expect_one()?;
    }
    let m = NewMember {
        id: owner.membership_id,
        user_id: owner.user_id,
        role: TenantRole::Owner,
        kind: MembershipKind::Primary,
        status: MembershipStatus::Active,
        parent_membership_id: None,
        department_id: None,
        display_name_enc: owner.display_name_enc.clone(),
    };
    let owner_id = memberships::insert_row(inner, t.id, None, &m, now).await?;
    Ok(CreatedTenant {
        tenant: t.id,
        owner: owner_id,
    })
}

fn map_tenant(tx: &TenantTx, row: &sqlx::mysql::MySqlRow) -> Result<TenantRow, DbError> {
    let id = TenantId(sql::uuid_col(row, "id")?);
    tx.assert_row_tenant(id)?;
    Ok(TenantRow {
        id,
        kind: sql::col(row, "kind")?,
        status: sql::col(row, "status")?,
        version: sql::col(row, "version")?,
        created_at: sql::col(row, "created_at")?,
    })
}

/// The tx tenant's own row.
///
/// # Errors
/// `NotFound`, `TenantMismatch`, server errors.
pub async fn get_own(tx: &mut TenantTx) -> Result<TenantRow, DbError> {
    let tid = tx.tid();
    let row = tx
        .inner
        .fetch_optional(sql::q(TENANTS_GET).bind(tid))
        .await?
        .ok_or(DbError::NotFound("tenant"))?;
    map_tenant(tx, &row)
}

/// Tenant MUTEX: `SELECT ... FOR UPDATE` on the tx tenant row. Returns its status.
///
/// # Errors
/// `NotFound`, `TenantMismatch`, server errors.
pub async fn lock_own(tx: &mut TenantTx) -> Result<String, DbError> {
    let tid = tx.tenant();
    lock_inner(&mut tx.inner, tid).await
}

/// Tenant mutex for crate-internal paths that already own the tenant id (tx tenant or a tenant created
/// in the same tx).
pub(crate) async fn lock_inner(
    inner: &mut crate::tx::Inner,
    tenant: TenantId,
) -> Result<String, DbError> {
    let row = inner
        .fetch_optional(sql::q(TENANTS_LOCK_FOR_UPDATE).bind(tenant.0))
        .await?
        .ok_or(DbError::NotFound("tenant"))?;
    crate::tx::assert_row_tenant(tenant, TenantId(sql::uuid_col(&row, "id")?))?;
    sql::col(&row, "status")
}

/// Staff sets `max_members` (`None` = unlimited) for the tenant of the verified grant.
///
/// # Errors
/// `NotPersisted` (no quota row = unknown tenant), server errors.
pub async fn set_max_members(
    tx: &mut PlatformTx,
    max_members: Option<u32>,
    now: OffsetDateTime,
) -> Result<(), DbError> {
    // Tenant = the one the verified staff grant is for (never a free argument).
    let tenant = tx.grant().tenant();
    let staff = tx.staff_user();
    tx.inner
        .execute(
            sql::q(TENANT_QUOTAS_SET_MAX_MEMBERS)
                .bind(max_members)
                .bind(staff.0)
                .bind(now)
                .bind(tenant.0),
        )
        .await?
        .expect_one()?;
    // Quota change is authz-affecting (DATABASE.md §4.4): epoch bump in the same tx.
    tx.inner
        .execute(sql::q(AUTHZ_EPOCHS_BUMP).bind(now).bind(tenant.0))
        .await?
        .expect_one()
}
